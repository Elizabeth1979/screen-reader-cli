export function generateTests(scanResults, options = {}) {
  const { framework = "playwright", output } = options;
  if (framework === "vitest") {
    return generateVitestTests(scanResults);
  }
  return generatePlaywrightTests(scanResults);
}

// One test per failing axe rule, asserted by axe itself via
// @axe-core/playwright. Hand-written re-checks drifted from axe — a link
// wrapping <img alt="Home"> or a button named by aria-labelledby failed them
// while being accessible — and rules without one became empty tests that
// always passed. Same engine as the scan means same verdict.
function generatePlaywrightTests(results) {
  const rules = [];
  const seen = new Set();
  for (const v of results.violations) {
    if (seen.has(v.id)) continue;
    seen.add(v.id);
    rules.push([v.id, v.message]);
  }

  if (rules.length === 0) return null;

  const urlPath = new URL(results.url).pathname;
  const ruleList = rules
    .map((r) => `  ${JSON.stringify(r)},`)
    .join("\n");
  return `// Accessibility regression tests
// Generated by screen-reader-cli from scan of ${results.url}
// ${new Date().toISOString()}
//
// Each test runs one axe-core rule that failed in the scan. It fails until
// the rule passes, then guards against regressions.
// Needs: npm install -D @playwright/test @axe-core/playwright

import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

const URL = ${JSON.stringify(results.url)};

// [axe rule id, what it checks]
const RULES = [
${ruleList}
];

test.describe(${JSON.stringify(`Accessibility: ${urlPath}`)}, () => {
  test.beforeEach(async ({ page }) => {
    await page.goto(URL);
  });

  for (const [rule, help] of RULES) {
    test(\`\${help} (\${rule})\`, async ({ page }) => {
      const { violations } = await new AxeBuilder({ page })
        .withRules([rule])
        .analyze();
      const failing = violations.flatMap((v) =>
        v.nodes.map((n) => n.target.join(' ')),
      );
      expect(failing, help).toEqual([]);
    });
  }
});
`;
}

function generateVitestTests(results) {
  const tests = [];
  const seen = new Set();

  for (const v of results.violations) {
    const key = v.id;
    if (seen.has(key)) continue;
    seen.add(key);

    tests.push(`  // ${v.message} (${v.id})
  // Suggestion: ${v.suggestion || ""}
  test.todo('${escQuote(v.message)}');`);
  }

  if (tests.length === 0) return null;

  return `// Accessibility regression tests (Vitest)
// Generated by screen-reader-cli from scan of ${results.url}
// ${new Date().toISOString()}
//
// TODO: Import your component and render it with @testing-library/react
// import { render, screen } from '@testing-library/react';
// import { expect, test, describe } from 'vitest';

import { expect, test, describe } from 'vitest';

describe('Accessibility: ${escQuote(results.title)}', () => {
${tests.join("\n\n")}
});
`;
}

function escQuote(str) {
  return String(str || "").replace(/'/g, "\\'").replace(/\n/g, " ");
}
